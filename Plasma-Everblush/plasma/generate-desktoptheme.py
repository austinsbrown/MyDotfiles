def tasks():
    d = Doc()
    d.maxw = 520
    stretch_hint(d)
    # 4px transparent gap around a 3px-radius rounded rect, like the docklike
    # plugin's `margin: 5 2.5; border-radius: 3` buttons.  Margins of 10 give a
    # 24px icon on a 44px panel (XFCE docklike iconSize=24).
    gap, r = 4, RAD_CONTROL
    sz = (gap + r,) * 4
    gaps = (gap,) * 4
    hints = {"top": 10, "bottom": 10, "left": 10, "right": 10}
    bar_color = "Highlight"
    states = [
        # name, fills, border, bar
        ("normal", [("Text", 0.04)], None, None),                  # GTK panel button rgba(255,255,255,.04)
        ("hover", [("Text", 0.07)], None, None),                   # GTK :hover .07
        ("launcher-hover", [("Text", 0.07)], None, None),
        ("focus", [("Text", 0.10)], None, (bar_color, 1)),         # GTK :checked .10 + accent bar
        ("focus-hover", [("Text", 0.13)], None, (bar_color, 1)),
        ("attention", [("NeutralText", 0.16)], None, ("NeutralText", 1)),
        ("attention-hover", [("NeutralText", 0.22)], None, ("NeutralText", 1)),
        ("minimized", [("Text", 0.001)], ("Text", 0.12), None),
        ("progress", [("PositiveText", 0.22)], None, None),
    ]
    locs = [("", "b"), ("north-", "t"), ("west-", "l"), ("east-", "r")]
    for loc, side in locs:
        for name, fills, border, bar in states:
            bars = ((side, 2) + bar,) if bar else ()
            frame(d, loc + name, sizes=sz, radius=r, gaps=gaps, fills=fills, border=border,
                  bars=bars, hints=hints, center=(22, 22))
    # Group-expander badge: small accent chevron pointing away from the screen edge.
    chev = {"bottom": "M2.5 7 5.5 4 8.5 7", "top": "M2.5 4 5.5 7 8.5 4",
            "left": "M4 2.5 7 5.5 4 8.5", "right": "M7 2.5 4 5.5 7 8.5"}
    for side, dpath in chev.items():
        sized_group(d, "group-expander-%s" % side, 11, 11,
                    '<path d="%s" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" '
                    'stroke-linejoin="round" class="ColorScheme-Highlight"/>' % dpath)
    d.write("widgets/tasks.svg")


