#!/usr/bin/env python3
"""Generate the Everblush Plasma Style (desktoptheme) SVGs.

Run:  python3 generate-desktoptheme.py   (writes ./desktoptheme/Everblush/...)

Every frame SVG is built from one routine (frame()) that emits the 9 KSvg
frame pieces (<prefix>-topleft ... <prefix>-bottomright) plus hint elements,
so geometry and element IDs stay consistent across files.
Colours come from the ColorScheme-* stylesheet classes (driven by the theme's
baked `colors` file); only the subtle white border (rgba(255,255,255,.07),
from the Everblush GTK theme) is hard-coded.
"""
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "desktoptheme", "Everblush")

# Default colours used by the stylesheet (KSvg replaces them at runtime).
SCHEME = {
    "Text": "#dadada", "Background": "#21282a", "Highlight": "#6695a3",
    "HighlightedText": "#ffffff", "ViewText": "#dadada", "ViewBackground": "#181f21",
    "ViewHover": "#6695a3", "ViewFocus": "#6695a3", "ButtonText": "#dadada",
    "ButtonBackground": "#2c3335", "ButtonHover": "#6695a3", "ButtonFocus": "#6695a3",
    "PositiveText": "#8ccf7e", "NeutralText": "#e5c76b", "NegativeText": "#e06e6e",
}
BORDER = ("#ffffff", 0.07)       # GTK @borders
PIECES = ["topleft", "top", "topright", "left", "center", "right",
          "bottomleft", "bottom", "bottomright"]
TOUCH = {  # which outer sides each piece touches
    "topleft": "tl", "top": "t", "topright": "tr", "left": "l", "center": "",
    "right": "r", "bottomleft": "bl", "bottom": "b", "bottomright": "br"}


def f(v):
    s = ("%.4f" % v).rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def paint(color, opacity=1.0):
    """color: ColorScheme class name (e.g. 'Text') or '#hex'."""
    op = "" if opacity >= 1 else ' fill-opacity="%s"' % f(opacity)
    if color.startswith("#"):
        return 'fill="%s"%s' % (color, op)
    return 'class="ColorScheme-%s" fill="currentColor"%s' % (color, op)


class Doc:
    def __init__(self):
        self.items = []
        self.defs = []
        self.x = 2
        self.y = 2
        self.rowh = 0
        self.maxw = 420
        self.w = 0
        self.h = 0

    def place(self, w, h):
        """Reserve a w*h slot on the canvas; returns its origin."""
        if self.x + w > self.maxw and self.x > 2:
            self.x = 2
            self.y += self.rowh + 6
            self.rowh = 0
        ox, oy = self.x, self.y
        self.x += w + 6
        self.rowh = max(self.rowh, h)
        self.w = max(self.w, ox + w + 2)
        self.h = max(self.h, oy + h + 2)
        return ox, oy

    def add(self, s):
        self.items.append(s)

    def hint(self, id_, w, h, color="#ff00ff"):
        ox, oy = self.place(max(w, 1), max(h, 1))
        self.add('<rect id="%s" x="%s" y="%s" width="%s" height="%s" fill="%s" opacity="0.6"/>'
                 % (id_, f(ox), f(oy), f(w if w > 0 else 1e-8), f(h if h > 0 else 1e-8), color))

    def write(self, path):
        style = "\n".join("      .ColorScheme-%s { color:%s; stop-color:%s; }" % (k, v, v)
                          for k, v in SCHEME.items())
        out = ['<?xml version="1.0" encoding="UTF-8"?>',
               '<!-- Everblush Plasma Style - generated by plasma/generate-desktoptheme.py. GPL-3.0 -->',
               '<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" '
               'version="1.1" width="%d" height="%d" viewBox="0 0 %d %d">' % (self.w, self.h, self.w, self.h),
               '  <defs>',
               '    <style id="current-color-scheme" type="text/css">',
               style,
               '    </style>']
        out += ["    " + d for d in self.defs]
        out += ['  </defs>']
        out += ["  " + i for i in self.items]
        out.append('</svg>')
        full = os.path.join(OUT, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w") as fh:
            fh.write("\n".join(out) + "\n")
        print("wrote", full)


def region(piece, pw, ph, ins, rr):
    """Path of the visible area of a frame piece in local coords.
    ins: dict side->inset (only applied on sides the piece touches)."""
    t = TOUCH[piece]
    il = ins["l"] if "l" in t else 0
    it = ins["t"] if "t" in t else 0
    ir = ins["r"] if "r" in t else 0
    ib = ins["b"] if "b" in t else 0
    x0, y0, x1, y1 = il, it, pw - ir, ph - ib
    if x1 <= x0 or y1 <= y0:
        return ""
    if len(t) == 2 and rr > 0:
        a = "A%s %s 0 0 1 " % (f(rr), f(rr))
        if t == "tl":
            return "M%s %sV%s%s%s %sH%sV%sZ" % (f(x0), f(y1), f(y0 + rr), a, f(x0 + rr), f(y0), f(x1), f(y1))
        if t == "tr":
            return "M%s %sH%s%s%s %sV%sH%sZ" % (f(x0), f(y0), f(x1 - rr), a, f(x1), f(y0 + rr), f(y1), f(x0))
        if t == "br":
            return "M%s %sH%sV%s%s%s %sH%sZ" % (f(x0), f(y0), f(x1), f(y1 - rr), a, f(x1 - rr), f(y1), f(x0))
        if t == "bl":
            return "M%s %sV%sH%s%s%s %sV%sZ" % (f(x1), f(y0), f(y1), f(x0 + rr), a, f(x0), f(y1 - rr), f(y0))
    return "M%s %sH%sV%sH%sZ" % (f(x0), f(y0), f(x1), f(y1), f(x0))


def frame(doc, prefix, sizes=(6, 6, 6, 6), radius=5, gaps=(0, 0, 0, 0), fills=(("Background", 1),),
          border=None, border_sides="tlrb", radii=None, bars=(), seps=(), hints=None,
          center=(16, 16), insets=None, mask=False):
    """Emit a 9-piece KSvg frame.

    sizes/gaps: (left, top, right, bottom) piece sizes / transparent outer gaps.
    fills:  list of (color, opacity) layers filling the rounded rect.
    border: (color, opacity) 1px inside border along border_sides.
    radii:  per-corner radius dict {'tl':..} (default: radius where both sides bordered or border is None).
    bars:   list of (side, thickness, color, opacity) indicator bars drawn inside the edge piece of `side`.
    seps:   list of (side, color, opacity) 1px lines on a side (for headings).
    hints:  dict margin-side -> value for <prefix>-hint-<side>-margin (None = no hints).
    insets: dict side -> value for <prefix>-hint-<side>-inset.
    mask:   also emit mask-<piece> elements (black shape) for blur/input masks.
    """
    L, T, R, B = sizes
    gl, gt, gr, gb = gaps
    cw, ch = center
    W, H = L + cw + R, T + ch + B
    pre = prefix + "-" if prefix else ""
    corner_of = {"topleft": "tl", "topright": "tr", "bottomleft": "bl", "bottomright": "br"}
    if radii is None:
        radii = {}
        for c in ("tl", "tr", "bl", "br"):
            ok = border is None or (c[0] in border_sides and c[1] in border_sides)
            radii[c] = radius if ok else 0
    geo = {"topleft": (0, 0, L, T), "top": (L, 0, cw, T), "topright": (L + cw, 0, R, T),
           "left": (0, T, L, ch), "center": (L, T, cw, ch), "right": (L + cw, T, R, ch),
           "bottomleft": (0, T + ch, L, B), "bottom": (L, T + ch, cw, B), "bottomright": (L + cw, T + ch, R, B)}
    g = {"l": gl, "t": gt, "r": gr, "b": gb}

    def emit(idprefix, maskmode):
        ox, oy = doc.place(W, H)
        for p in PIECES:
            px, py, pw, ph = geo[p]
            rr = radii.get(corner_of.get(p, ""), 0)
            parts = ['<rect width="%s" height="%s" fill="#000000" fill-opacity="0.001"/>' % (f(pw), f(ph))]
            base = region(p, pw, ph, g, rr)
            if maskmode:
                if base:
                    parts.append('<path d="%s" fill="#000000"/>' % base)
            else:
                if base:
                    for col, op in fills:
                        parts.append('<path d="%s" %s/>' % (base, paint(col, op)))
                if border and base:
                    ins1 = {s: g[s] + (1 if s in border_sides else 0) for s in "ltrb"}
                    t = TOUCH[p]
                    if any(s in border_sides for s in t):
                        inner = region(p, pw, ph, ins1, max(rr - 1, 0) if rr else 0)
                        parts.append('<path d="%s %s" fill-rule="evenodd" %s/>' % (base, inner, paint(*border)))
                for side, col, op in seps:
                    t = TOUCH[p]
                    if side in t or p == "center":
                        if p == "center":
                            continue
                        # 1px line along `side`, skipping bordered perpendicular sides
                        x0 = (g["l"] + (1 if ("l" in border_sides and "l" in t) else 0)) if "l" in t else 0
                        x1 = pw - ((g["r"] + (1 if ("r" in border_sides and "r" in t) else 0)) if "r" in t else 0)
                        y0 = (g["t"] + (1 if ("t" in border_sides and "t" in t) else 0)) if "t" in t else 0
                        y1 = ph - ((g["b"] + (1 if ("b" in border_sides and "b" in t) else 0)) if "b" in t else 0)
                        if side == "b":
                            y0 = ph - g["b"] - 1; y1 = ph - g["b"]
                        elif side == "t":
                            y0 = g["t"]; y1 = g["t"] + 1
                        elif side == "l":
                            x0 = g["l"]; x1 = g["l"] + 1
                        elif side == "r":
                            x0 = pw - g["r"] - 1; x1 = pw - g["r"]
                        parts.append('<rect x="%s" y="%s" width="%s" height="%s" %s/>'
                                     % (f(x0), f(y0), f(x1 - x0), f(y1 - y0), paint(col, op)))
                for side, th, col, op in bars:
                    edge = {"b": "bottom", "t": "top", "l": "left", "r": "right"}[side]
                    if p != edge:
                        continue
                    if side == "b":
                        x, y, w, h = 0, ph - g["b"] - th, pw, th
                    elif side == "t":
                        x, y, w, h = 0, g["t"], pw, th
                    elif side == "l":
                        x, y, w, h = g["l"], 0, th, ph
                    else:
                        x, y, w, h = pw - g["r"] - th, 0, th, ph
                    parts.append('<rect x="%s" y="%s" width="%s" height="%s" %s/>'
                                 % (f(x), f(y), f(w), f(h), paint(col, op)))
            doc.add('<g id="%s%s" transform="translate(%s %s)">%s</g>'
                    % (idprefix, p, f(ox + px), f(oy + py), "".join(parts)))

    emit(pre, False)
    if mask:
        emit("mask-" + pre, True)
    if hints:
        for side in ("top", "bottom", "left", "right"):
            v = hints[side]
            if side in ("top", "bottom"):
                doc.hint("%shint-%s-margin" % (pre, side), 2, v)
            else:
                doc.hint("%shint-%s-margin" % (pre, side), v, 2)
    if insets:
        for side in ("top", "bottom", "left", "right"):
            v = insets[side]
            if side in ("top", "bottom"):
                doc.hint("%shint-%s-inset" % (pre, side), 2, v, "#00ff00")
            else:
                doc.hint("%shint-%s-inset" % (pre, side), v, 2, "#00ff00")


SHADOW_STOPS = [(0.0, 1.0), (0.2, 0.62), (0.45, 0.28), (0.7, 0.09), (1.0, 0.0)]


def shadows(doc, extent=10, radius=5, overlap=6, strength=0.30, prefix="shadow", hint_insets=True):
    """Soft drop-shadow tiles (shadow-*) for a frame with corner `radius`.

    Like Breeze, every tile reaches `overlap` px (= frame piece size) under the
    window; the visible shadow is `extent` px wide (= shadow-hint-*-margin)."""
    e, r, o = extent, radius, overlap
    S = o + e                      # tile depth
    L = 16                         # centre size of the drawing
    gid = "%s-grad" % prefix
    lin = "".join('<stop offset="%s" stop-color="#000000" stop-opacity="%s"/>' % (f(t), f(a * strength))
                  for t, a in SHADOW_STOPS)
    R = r + e
    rad = '<stop offset="0" stop-color="#000000" stop-opacity="%s"/>' % f(strength)
    rad += "".join('<stop offset="%s" stop-color="#000000" stop-opacity="%s"/>'
                   % (f((r + t * e) / R), f(a * strength)) for t, a in SHADOW_STOPS)
    c = o - r                      # rounding centre (local coords)
    # Tiles are authored as the bottom-right / right variants (window at x<o, y<o)
    # and mirrored or rotated for the other sides.
    doc.defs.append('<linearGradient id="%s-side" gradientUnits="userSpaceOnUse" x1="%s" y1="0" x2="%s" y2="0">%s</linearGradient>'
                    % (gid, f(o), f(S), lin))
    doc.defs.append('<radialGradient id="%s-corner" gradientUnits="userSpaceOnUse" cx="%s" cy="%s" r="%s">%s</radialGradient>'
                    % (gid, f(c), f(c), f(R), rad))
    # tile minus the window's rounded corner (window covers x<o, y<o)
    corner = ('<rect width="%s" height="%s" fill="#000000" fill-opacity="0.001"/>' % (f(S), f(S)) +
              '<path d="M%s 0H%sV%sH0V%sH%sA%s %s 0 0 0 %s %sZ" fill="url(#%s-corner)"/>'
              % (f(o), f(S), f(S), f(o), f(c), f(r), f(r), f(o), f(c), gid))
    side_len = L - 2 * o
    side = ('<rect width="%s" height="%s" fill="#000000" fill-opacity="0.001"/>'
            '<rect x="%s" width="%s" height="%s" fill="url(#%s-side)"/>'
            % (f(S), f(side_len), f(o), f(e), f(side_len), gid))
    ox, oy = doc.place(L + 2 * e, L + 2 * e)
    cx, cy = ox + e, oy + e        # top-left of the "window"
    x1, y1 = cx + L - o, cy + L - o  # local origin for right / bottom tiles
    x0, y0 = cx + o, cy + o          # local origin for left / top tiles (mirrored)
    t = {
        "bottomright": "translate(%s %s)" % (f(x1), f(y1)),
        "topright": "translate(%s %s) scale(1 -1)" % (f(x1), f(y0)),
        "bottomleft": "translate(%s %s) scale(-1 1)" % (f(x0), f(y1)),
        "topleft": "translate(%s %s) scale(-1 -1)" % (f(x0), f(y0)),
    }
    for n, tr in t.items():
        doc.add('<g id="%s-%s" transform="%s">%s</g>' % (prefix, n, tr, corner))
    doc.add('<g id="%s-right" transform="translate(%s %s)">%s</g>' % (prefix, f(x1), f(y0), side))
    doc.add('<g id="%s-left" transform="translate(%s %s) scale(-1 1)">%s</g>' % (prefix, f(x0), f(y0), side))
    doc.add('<g id="%s-bottom" transform="translate(%s %s) rotate(90) scale(1 -1)">%s</g>'
            % (prefix, f(x0), f(y1), side))
    doc.add('<g id="%s-top" transform="translate(%s %s) rotate(-90)">%s</g>'
            % (prefix, f(x0), f(y0), side))
    doc.add('<rect id="%s-center" x="%s" y="%s" width="%s" height="%s" fill="#000000" fill-opacity="0.001"/>'
            % (prefix, f(x0), f(y0), f(side_len), f(side_len)))
    for sd in ("top", "bottom", "left", "right"):
        if sd in ("top", "bottom"):
            doc.hint("%s-hint-%s-margin" % (prefix, sd), 2, e)
        else:
            doc.hint("%s-hint-%s-margin" % (prefix, sd), e, 2)
    if hint_insets:
        for sd in ("top", "bottom", "left", "right"):
            if sd in ("top", "bottom"):
                doc.hint("%s-hint-%s-inset" % (prefix, sd), 2, e, "#00ff00")
            else:
                doc.hint("%s-hint-%s-inset" % (prefix, sd), e, 2, "#00ff00")


def stretch_hint(doc):
    ox, oy = doc.place(4, 4)
    doc.add('<rect id="hint-stretch-borders" x="%s" y="%s" width="4" height="4" fill="#ff2a2a" opacity="0.6"/>' % (f(ox), f(oy)))


def zero_insets(doc, prefix=""):
    pre = prefix + "-" if prefix else ""
    for s in ("top", "bottom"):
        doc.hint("%shint-%s-inset" % (pre, s), 4, 0, "#00ff00")
    for s in ("left", "right"):
        doc.hint("%shint-%s-inset" % (pre, s), 0, 4, "#00ff00")


# ---------------------------------------------------------------------------
# Surfaces: dialogs, tooltips, panel, desktop widget background
# ---------------------------------------------------------------------------
RAD_SURFACE = 5   # popups / panel / tooltips (xfwm tabwin 5px, GTK popover 3px)
RAD_CONTROL = 3   # buttons, task items, list items (eww / GTK panel buttons 3px)


def popup_surface(path, margin=5, shadow_strength=0.30):
    d = Doc()
    stretch_hint(d)
    frame(d, "", sizes=(6, 6, 6, 6), radius=RAD_SURFACE, fills=(("Background", 1),), border=BORDER,
          hints={"top": margin, "bottom": margin, "left": margin, "right": margin}, mask=True)
    zero_insets(d)
    shadows(d, extent=10, radius=RAD_SURFACE, strength=shadow_strength)
    d.write(path)


def panel_surface(path, alpha=1.0):
    d = Doc()
    stretch_hint(d)
    # Flat #21282a bar.  Only the screen-facing borders are disabled by
    # Plasma, so a docked bottom panel shows just its 1px top highlight line;
    # a floating panel gets the full rounded, bordered shape.  The translucent
    # variant relies on the mask-* pieces for KWin's blur-behind region.
    frame(d, "", sizes=(6, 6, 6, 6), radius=RAD_SURFACE, fills=(("Background", alpha),), border=BORDER,
          hints={"top": 4, "bottom": 4, "left": 4, "right": 4}, mask=True)
    zero_insets(d)
    ox, oy = d.place(16, 16)
    d.add('<rect id="thick-center" x="%s" y="%s" width="16" height="16" %s/>' % (f(ox), f(oy), paint("Background", alpha)))
    for s in ("top", "bottom"):
        d.hint("thick-hint-%s-margin" % s, 2, 8)
    for s in ("left", "right"):
        d.hint("thick-hint-%s-margin" % s, 8, 2)
    shadows(d, extent=8, radius=RAD_SURFACE, strength=0.22)
    d.write(path)


def widget_background(path, alpha=1.0):
    d = Doc()
    stretch_hint(d)
    frame(d, "", sizes=(6, 6, 6, 6), radius=RAD_SURFACE, fills=(("Background", alpha),), border=BORDER,
          hints={"top": 8, "bottom": 8, "left": 8, "right": 8}, mask=True)
    zero_insets(d)
    shadows(d, extent=10, radius=RAD_SURFACE, strength=0.30)
    d.write(path)


def plasmoidheading():
    d = Doc()
    stretch_hint(d)
    # Must line up with dialogs/background: same 6px pieces, radius, 1px border.
    frame(d, "header", sizes=(6, 6, 6, 6), radius=RAD_SURFACE, fills=(("Background", 1),), border=BORDER,
          border_sides="tlr", radii={"tl": RAD_SURFACE, "tr": RAD_SURFACE, "bl": 0, "br": 0},
          seps=(("b",) + BORDER,))
    frame(d, "footer", sizes=(6, 6, 6, 6), radius=RAD_SURFACE, fills=(("Background", 1),), border=BORDER,
          border_sides="blr", radii={"tl": 0, "tr": 0, "bl": RAD_SURFACE, "br": RAD_SURFACE},
          seps=(("t",) + BORDER,))
    for s in ("top", "bottom"):
        d.hint("hint-%s-margin" % s, 4, 6)
    for s in ("left", "right"):
        d.hint("hint-%s-margin" % s, 6, 4)
    d.write("widgets/plasmoidheading.svg")


