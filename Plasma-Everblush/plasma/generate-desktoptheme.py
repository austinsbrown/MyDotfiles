def viewitem():
    d = Doc()
    stretch_hint(d)
    r = RAD_CONTROL
    for name, fills in [("normal", [("Text", 0.001)]),
                        ("hover", [("Text", 0.06)]),            # = #2c3335 over #21282a
                        ("selected", [("Highlight", 0.35)]),
                        ("selected+hover", [("Highlight", 0.45)])]:
        frame(d, name, sizes=(5, 5, 5, 5), radius=r, fills=fills)
    d.write("widgets/viewitem.svg")


def listitem():
    d = Doc()
    stretch_hint(d)
    r = RAD_CONTROL
    m = {"top": 6, "bottom": 6, "left": 6, "right": 6}
    for name, fills in [("normal", [("Text", 0.001)]),
                        ("hover", [("Text", 0.06)]),
                        ("pressed", [("Highlight", 0.35)]),
                        ("section", [("Text", 0.04)])]:
        frame(d, name, sizes=(3, 3, 3, 3), radius=r, fills=fills,
              hints=None if name == "hover" else m)
    ox, oy = d.place(40, 1)
    d.add('<rect id="separator" x="%s" y="%s" width="40" height="1" %s/>' % (f(ox), f(oy), paint("Text", 0.12)))
    d.write("widgets/listitem.svg")


def button():
    d = Doc()
    d.maxw = 360
